function tocHtml() {
  /* Pack whole sections into two columns — a 部 must never straddle the
     column break, or the contents page reads as two unrelated lists. */
  const HEAD = 30, ROW = 24, GAP = 14, COLX = [0, 470];
  const blocks = SECTIONS.slice(1).map((s) => {
    const list = pages.filter((p) => p.key === s.key && p.title);
    return { mark: s.mark, list, h: HEAD + list.length * ROW };
  });

  const cols = [[], []];
  let ci = 0, used = 0;
  for (const b of blocks) {
    const need = (used ? GAP : 0) + b.h;
    if (used + need > H && ci === 0) { ci = 1; used = 0; }
    cols[ci].push(b);
    used += used ? GAP + b.h : b.h;
  }
  if (used > H) console.log(`\u26a0  contents column ${ci + 1} overflows by ${used - H}px`);

  let html = '';
  cols.forEach((col, i) => {
    let y = 0;
    for (const b of col) {
      html += `<div class="tocsec" style="left:${COLX[i]}px;top:${y}px">${b.mark}</div>`;
      y += HEAD;
      for (const p of b.list) {
        const no = p.drill ? String(p.drill).padStart(2, '0') : '\u2014';
        const label = `${p.han || ''} ${p.latin || ''}`.trim()
          || p.title.replace(/<[^>]+>/g, ' ').trim();
        html += `<a class="tocrow" href="#${aid(p.id)}" style="left:${COLX[i]}px;top:${y}px">`
          + `<span class="n">${no}</span>&nbsp;&nbsp;<span class="t">${label}</span>`
          + `<span class="n">&nbsp;&nbsp;&middot;&nbsp;${p.folio}</span></a>`;
        y += ROW;
      }
      y += GAP;
    }
  });
  return html;
}

