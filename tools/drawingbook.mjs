    s+=`<mask id="sm${id}"><circle cx="${cx}" cy="${cy}" r="${r}" fill="white"/>`
      +`<circle cx="${(cx-r*0.5).toFixed(1)}" cy="${(cy-r*0.5).toFixed(1)}" r="${(r*1.02).toFixed(1)}" fill="black"/></mask>`
